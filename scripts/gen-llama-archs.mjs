// Writes src/engines/llamaArchs.ts: the model architectures the llama.cpp bundled with llama.rn
// can load. Run it after upgrading llama.rn (npm run gen:archs), so the Cookbook stops flagging
// models the new llama.cpp supports, and flags the ones it dropped.
//
// An architecture counts when llama.cpp knows its name (LLM_ARCH_NAMES in llama-arch.cpp) and
// has an implementation for it (llama_model_mapping in llama-model.cpp).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const llamaRn = join(root, 'node_modules', 'llama.rn');
const src = join(llamaRn, 'vendor', 'llama.cpp', 'src');
const out = join(root, 'src', 'engines', 'llamaArchs.ts');

const version = JSON.parse(readFileSync(join(llamaRn, 'package.json'), 'utf8')).version;

/** The text from `start` up to the first line that is just `end`. */
function block(text, start, end) {
  const from = text.indexOf(start);
  if (from < 0) throw new Error(`Couldn't find "${start}"; llama.cpp's layout changed, update this script.`);
  const to = text.indexOf(end, from);
  return text.slice(from, to < 0 ? undefined : to);
}

const names = new Map(
  [...block(readFileSync(join(src, 'llama-arch.cpp'), 'utf8'), 'LLM_ARCH_NAMES', '\n};')
    .matchAll(/\{\s*(LLM_ARCH_\w+)\s*,\s*"([^"]+)"\s*\}/g)]
    .map((m) => [m[1], m[2]])
);
const implemented = new Set(
  [...block(readFileSync(join(src, 'llama-model.cpp'), 'utf8'), 'llama_model_mapping(', '\n}\n')
    .matchAll(/case (LLM_ARCH_\w+):/g)]
    .map((m) => m[1])
);

const archs = [...names].filter(([id]) => implemented.has(id)).map(([, name]) => name);
if (archs.length < 50) throw new Error(`Found only ${archs.length} architectures; llama.cpp's layout changed, update this script.`);

const lines = [];
for (let i = 0; i < archs.length; i += 8) lines.push(`  ${archs.slice(i, i + 8).map((a) => `'${a}'`).join(', ')},`);

writeFileSync(
  out,
  `// Generated by scripts/gen-llama-archs.mjs from the llama.cpp in llama.rn ${version}.
// Don't edit by hand: run \`npm run gen:archs\` after upgrading llama.rn.

export const LLAMA_RN_VERSION = '${version}';

/** Model architectures (GGUF \`general.architecture\`) this llama.cpp can load. */
export const LLAMA_ARCHS: readonly string[] = [
${lines.join('\n')}
];
`
);
console.log(`Wrote ${archs.length} architectures from llama.rn ${version} to ${out}`);
